Ingredients:
  1.00     ea.         20 oz. Apple Pie Filling
  1.00     T          Butter
  1.00     t          Lemon juice
  1.00     ea.         Dash of cinnamon
  1.00     c          Prepared biscuit mix
  0.33     c          Milk

Instructions:
Pour apple pie filling into a 9-inch pie plate.  Dot with butter;
sprinkle with lemon juice and cinnamon.  Place in 400 oven for about 10
minutes, or until mixture is hot and bubbly.  Meanwhile combine biscuit
mix and 2 tablespoons soft butter, stir in milk.  Drop by spoonful on
hot apple mixture.  Continue baking 20-25 minutes or until biscuits are
done. Serve warm with cream.


